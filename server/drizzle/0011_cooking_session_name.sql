-- HomeChef v0.2.1.1：烹饪记录的**自定义名称**
--
-- 目标
-- ────
--   给 `cooking_session` 增加**可空**列 `name`，用于用户自定义的记录名称。
--
-- 语义（与前端约定一致）
-- ──────────────────────
--   `name IS NULL`      → 使用**默认名称**：由 `started_at`
--                         （无法解析时回退 `created_at`）在**客户端本地时区**
--                         渲染为 `YYYY-MM-DD-HH:mm`，例如 `2026-10-15-21:30`。
--   `name IS NOT NULL`  → 用户自定义名称，列表与详情都原样显示。
--
-- ⚠️ 本次迁移**不回填、不改写任何历史行**
-- ─────────────────────────────────────
--   历史记录一律保持 `name = NULL`，即继续显示默认名。
--   仓库中**不存在**旧的名称列，因此无需、也不得伪造历史名称迁移。
--
-- ⚠️ **不修改 `started_at` / `created_at`**
--   名称与时间排序**无关**：列表排序仍完全由 `started_at`（其次 `id`）决定，
--   改名不会移动记录位置。
--
-- ⚠️ 校验位置
--   - 「空串 / 纯空白」由 **Service 层**拒绝（业务上等同「未填写」）；
--     若要恢复默认名，前端传 `null`，与空白输入**语义不同**。
--   - 长度上限同样由 Service 层校验，并与前端 `maxLength` 保持一致。
--   因此本列**刻意不设 CHECK**：约束若写在这里，两边规则容易走偏。
--
-- ⚠️⚠️ 严禁出现 `PRAGMA` / `BEGIN` / `COMMIT`
--   Drizzle 迁移器把**全部待应用迁移**包在同一个事务里，
--   上述语句会提前结束事务，破坏「失败整体回滚」的保证。
--
-- ⚠️ 不修改任何旧 migration。
--
-- 回滚
-- ────
--   SQLite 3.35+ 支持 `ALTER TABLE ... DROP COLUMN`（本项目 better-sqlite3
--   内置版本满足），因此可安全回退：见交付说明中的回退 SQL。

ALTER TABLE `cooking_session` ADD COLUMN `name` text;
