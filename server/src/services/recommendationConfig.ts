export const HISTORY_HALF_LIFE_DAYS = 7

/** 与「近期已做完的同一套菜」完全重合时的额外惩罚 */
export const ROTATION_REPEAT_PENALTY = 60

/**
 * 每日确定性轮换幅度（分）。
 *
 * ⚠️ 用「日期 + 方案签名」的稳定哈希产生 ±该幅度的偏移，
 *    **不使用随机数、不写曝光记录**：同一天同一方案必然同结果。
 */
export const ROTATION_AMPLITUDE = RECOMMENDATION_WEIGHTS.rotation_amplitude

/**
 * 用量覆盖分桶（v0.2.3 排序用）。
 *
 * ⚠️ 排序规则是「等级 → 主缺口 → 用量覆盖 → 软评分」。
 *    若覆盖比例不设分桶，浮点差异会让软评分**几乎永远无法生效**；
 *    分桶后，「覆盖程度相差不到 5%」的方案才由软评分决定先后，
 *    既保证库存优先，又让偏好/历史/轮换真正起作用。
 */
export const QUANTITY_COVERAGE_BUCKET = 0.05

